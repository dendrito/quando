# Polish says hours as ordinals: "o ósmej", "na ósmą", "ósma".
PL_ORD = {
    'pierwsz': 1, 'drug': 2, 'trzeci': 3, 'czwart': 4, 'piąt': 5, 'szóst': 6, 'siódm': 7, 'ósm': 8,
    'dziewiąt': 9, 'dziesiąt': 10, 'jedenast': 11, 'dwunast': 12, 'trzynast': 13, 'czternast': 14,
    'piętnast': 15, 'szesnast': 16, 'siedemnast': 17, 'osiemnast': 18, 'dziewiętnast': 19, 'dwudziest': 20,
}


def polish_ordinals():
    out = {}
    for stem, n in PL_ORD.items():
        for end in ('a', 'ą', 'iej' if stem == 'drug' else 'ej'):
            out[stem + end] = n
    for stem, n in [('pierwsz', 1), ('drug', 2), ('trzeci', 3)]:
        for end in ('a', 'ą', 'iej' if stem == 'drug' else 'ej'):
            for e20 in ('a', 'ą', 'ej'):
                out[f'dwudziest{e20} {stem}{end}'] = 20 + n
    return out


def words(lang):
    out = {}
    for n in range(0, 60):
        w = num2words(n, lang=lang).replace('-', ' ').strip()
        out[w] = n
        if lang == 'tr' and n > 10:
            # "on iki" and "oniki" are both typed.
            tens = num2words(n - n % 10, lang=lang)
            ones = num2words(n % 10, lang=lang) if n % 10 else ''
            out[f'{tens} {ones}'.strip()] = n
            out[f'{tens}{ones}'] = n
        if lang == 'ar' and ' و ' in w:
            out[w.replace(' و ', ' و')] = n
    out.update(EXTRA.get(lang, {}))
    if lang == 'pl':
        out.update(polish_ordinals())
    for s in SKIP.get(lang, ()):
        out.pop(s, None)
    return out


def main():
    lines = [
        '// Generated by tool/parser_words/build_numbers.py. Do not edit by hand;',
        '// add words to EXTRA there and run it again.',
        '',
        '/// Number words 0-59 by language, for the phrasebook.',
        'const spokenNumberWords = <String, Map<String, int>>{',
    ]
    for lang in LANGS + ['hi']:
        ws = words(lang) if lang != 'hi' else dict(EXTRA['hi'])
        lines.append(f"  '{lang}': {{")
        for w, n in sorted(ws.items(), key=lambda kv: (-len(kv[0]), kv[0])):
            esc = w.replace("'", "\\'")
            lines.append(f"    '{esc}': {n},")
        lines.append('  },')
    lines.append('};')
    dest = Path(__file__).resolve().parents[2] / 'lib/features/assistant/domain/words/numbers.g.dart'
    dest.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(dest)


if __name__ == '__main__':
    main()
