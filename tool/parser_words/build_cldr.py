"""Writes lib/features/assistant/domain/words/cldr.g.dart from Unicode CLDR
(https://cldr.unicode.org, Unicode license): the official weekday names,
today/tomorrow, morning/afternoon words and "in {0} minutes" phrasings for
each of Quando?'s 20 languages, so the parser never relies on a hand-typed
list for them.

Usage: python3 tool/parser_words/build_cldr.py <dir with <lang>/ca-gregorian.json and dateFields.json>
(from https://github.com/unicode-org/cldr-json, cldr-dates-full/main).
"""
import json
import sys
import unicodedata
from pathlib import Path

LANGS = ['en', 'pt', 'es', 'fr', 'de', 'it', 'nl', 'pl', 'ru', 'uk', 'tr', 'ar', 'he', 'hi', 'id', 'ja', 'ko',
         'zh', 'zh-Hant', 'vi']
# The parser strips accents for these before reading.
PLAIN = {'en', 'pt', 'es', 'fr', 'de', 'it'}
DAY_KEYS = ['mon', 'tue', 'wed', 'thu', 'fri', 'sat', 'sun']


def plain(s, lang):
    s = s.lower().replace('-', ' ').replace(' ', ' ')
    if lang in PLAIN:
        s = s.replace('ß', 's')
        s = ''.join(c for c in unicodedata.normalize('NFD', s) if unicodedata.category(c) != 'Mn')
    return s.strip()


def dart(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$') + "'"


def main(src):
    src = Path(src)
    out = [
        '// Generated by tool/parser_words/build_cldr.py from Unicode CLDR 48',
        '// (Unicode license). Do not edit by hand.',
        '',
        "import 'cldr_words.dart';",
        '',
        'const cldrWords = <String, CldrWords>{',
    ]
    for lang in LANGS:
        cal = json.load(open(src / lang / 'ca-gregorian.json'))['main'][lang]['dates']['calendars']['gregorian']
        fields = json.load(open(src / lang / 'dateFields.json'))['main'][lang]['dates']['fields']
        days = {}
        for ctx in ('format', 'stand-alone'):
            for width in ('wide',):
                for i, k in enumerate(DAY_KEYS):
                    days[plain(cal['days'][ctx][width][k], lang)] = i + 1
        rel = {}
        for k, n in (('relative-type-0', 0), ('relative-type-1', 1), ('relative-type-2', 2)):
            v = fields['day'].get(k)
            if v:
                rel[plain(v, lang)] = n
        periods = cal['dayPeriods']['format']['wide']
        def word(k):
            v = periods.get(k)
            # Skip "AM"/"a. m." style abbreviations: the parser has its own.
            return None if not v or '.' in v or v.isascii() and v.upper() == v else plain(v, lang)
        am = sorted({w for k in ('am', 'morning1', 'morning2') if (w := word(k))})
        # afternoon1 is midday (中午, mittags, 昼, siang) where an afternoon2
        # exists or the language says so: left to the noon words.
        pm_keys = ['pm', 'evening1', 'evening2', 'afternoon2']
        if 'afternoon2' not in periods and lang not in ('ja', 'id'):
            pm_keys.append('afternoon1')
        pm = sorted({w for k in pm_keys if (w := word(k))} - set(am))
        ins = {}
        for unit in ('minute', 'hour'):
            fut = fields[unit]['relativeTime-type-future']
            for v in fut.values():
                ins[plain(v, lang)] = unit
        key = lang.replace('-', '_')
        out.append(f"  '{key}': CldrWords(")
        out.append('    days: {' + ', '.join(f'{dart(k)}: {v}' for k, v in days.items()) + '},')
        out.append('    relativeDays: {' + ', '.join(f'{dart(k)}: {v}' for k, v in rel.items()) + '},')
        out.append('    morning: [' + ', '.join(dart(x) for x in am) + '],')
        out.append('    afternoon: [' + ', '.join(dart(x) for x in pm) + '],')
        out.append('    inTime: {' + ', '.join(f'{dart(k)}: {dart(v)}' for k, v in sorted(ins.items())) + '},')
        out.append('  ),')
    out.append('};')
    dest = Path(__file__).resolve().parents[2] / 'lib/features/assistant/domain/words/cldr.g.dart'
    dest.write_text('\n'.join(out) + '\n', encoding='utf-8')
    print(dest)


if __name__ == '__main__':
    main(sys.argv[1])
